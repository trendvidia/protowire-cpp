// genprint writes src/detail/go_isprint.inc: the code point ranges for which
// strconv.IsPrint holds. Run it from the repository root after a Go release
// moves Unicode, which the differential run reports:
//
//	go run ./tools/godiff/genprint > src/detail/go_isprint.inc
package main

import (
	"fmt"
	"runtime"
	"strconv"
	"unicode"
)

func main() {
	fmt.Printf("// Generated by tools/godiff/genprint from %s (Unicode %s). DO NOT EDIT.\n", runtime.Version(), unicode.Version)
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		p := r <= unicode.MaxRune && strconv.IsPrint(r)
		if p && start < 0 {
			start = r
		}
		if !p && start >= 0 {
			fmt.Printf("{0x%x, 0x%x},\n", start, r-1)
			start = -1
		}
	}
}
