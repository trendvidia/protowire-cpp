#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>

namespace protowire::detail {

// GoQuote quotes s exactly as Go's strconv.Quote does, so that every port
// names a map key alike in a path, an error message and Marshal's output.
std::string GoQuote(std::string_view s);

// GoIllegalRune is protowire-go's text for the character at the start of s,
// which no token starts with: `unexpected character ';'`, or `unexpected byte
// 0xff` for a byte that starts no valid UTF-8. *width is how many bytes it took.
std::string GoIllegalRune(std::string_view s, size_t* width);

// GoIsPrint is Go's strconv.IsPrint, from a table generated by
// tools/godiff/genprint. The table carries the Unicode version of the Go
// release that generated it, and the differential run compares every rune.
bool GoIsPrint(uint32_t rune);

}  // namespace protowire::detail
